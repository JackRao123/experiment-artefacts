"""Raw-Kineto gap attribution and same-run allocator evidence (no GPU work)."""
import collections
import json
import pickle
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
out = {}
for model in ('06b', '30b-a3b'):
    trace = json.loads((ROOT/f'qwen3-{model}.pt.trace.json').read_text())
    events = trace['traceEvents']
    kernels = sorted((e for e in events if e.get('cat') == 'kernel'), key=lambda e:e['ts'])
    cpu = {e.get('args', {}).get('External id'): e['name'] for e in events if e.get('cat')=='cpu_op'}
    gaps, buckets = collections.Counter(), collections.Counter()
    end = 0
    for event in kernels:
        if end and event['ts'] > end:
            gap = event['ts']-end
            gaps[cpu.get(event.get('args', {}).get('External id'), 'unknown')] += gap/1000
            buckets['<10us' if gap<10 else '10-100us' if gap<100 else '100us-1ms' if gap<1000 else '>=1ms'] += gap/1000
        end = max(end, event['ts']+event['dur'])
    with (ROOT/f'qwen3-{model}.memory.rank0.pickle').open('rb') as stream:
        snapshot = pickle.load(stream)  # trusted capture generated by this session
    allocations, actions = collections.Counter(), collections.Counter()
    for history in snapshot['device_traces']:
        for event in history:
            actions[event['action']] += 1
            if event['action'] == 'alloc':
                frames = [f for f in event.get('frames', []) if 'rope_utils' in f.get('filename', '')]
                if frames:
                    frame = frames[0]
                    allocations[f"{frame['name']}:{frame['line']}"] += event['size']
    flops = json.loads((ROOT/f'runs/qwen3-{model}-mfu.json').read_text())
    a = flops['forward_components_flops_per_token']['causal_attention']*40960
    fw = sum(e['dur'] for e in kernels if 'sdpa' in e['name'] and 'fprop' in e['name']) / 1e6
    bw = sum(e['dur'] for e in kernels if 'sdpa' in e['name'] and 'bprop' in e['name']) / 1e6
    out[model] = {
        'gap_buckets_ms': dict(buckets),
        'gap_next_cpu_owner_ms': dict(gaps.most_common(20)),
        'runtime_malloc_free_calls': [e['name'] for e in events if e.get('cat')=='cuda_runtime' and ('Malloc' in e['name'] or 'Free' in e['name'])],
        'memory_actions': dict(actions),
        'rope_cumulative_allocation_bytes': dict(allocations),
        'attention_forward_tflops_estimate': (2*a/fw)/1e12,
        'attention_backward_tflops_with_score_recompute_estimate': (2.5*a/bw)/1e12,
    }
(ROOT/'perfetto_analysis/supplement.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps(out,indent=2))
