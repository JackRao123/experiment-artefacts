OOM = {196608, 262144}
GPU_CAP = 178.35  # usable HBM per B200 (GiB)

fig, ax = plt.subplots(figsize=(11, 7))
seqs = sorted(DATA)
colors = cm.viridis([i / (len(seqs) - 1) for i in range(len(seqs))])

x = list(range(32))
for seq, color in zip(seqs, colors):
    ys = sorted(DATA[seq])  # sort ascending: x = sorted GPU rank
    oom = seq in OOM
    label = f"{seq // 1024}K" + (" (OOM)" if oom else "")
    ax.plot(
        x,
        ys,
        marker="o",
        markersize=3.5,
        linewidth=2,
        linestyle="--" if oom else "-",
        color=color,
        label=label,
    )

ax.axhline(
    GPU_CAP,
    color="red",
    linestyle=":",
    linewidth=1.5,
    label=f"B200 cap ({GPU_CAP:.0f} GiB)",
)
ax.set_xlabel("GPU rank (0-31, sorted ascending by memory.used)")
ax.set_ylabel("GPU memory.used (GiB)")
ax.set_title(
    "Nemotron-3-Ultra dropless (TP8/PP4/EP8/CP1) - per-GPU memory by sequence length\n"
    "U1-rerun; each curve = 32 GPUs sorted; right tail = hottest GPU (MoE imbalance)"
)
ax.set_xticks(range(0, 32, 2))
ax.grid(True, alpha=0.3)
ax.legend(title="max_seq_len", ncol=2, fontsize=9, loc="upper left")
fig.tight_layout()

out = "examples/ptt-nemotron3-super-sft/u1rerun_pergpu_mem.png"
